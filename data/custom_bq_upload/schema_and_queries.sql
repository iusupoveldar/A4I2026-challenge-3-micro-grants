  WHERE p_fail NOT BETWEEN 0 AND 1 OR n_failed>n_loans OR basis IS NULL)
  AS 'Invalid canonical rate metadata';

-- Keep every distinct location, including same-name branches. Start dates are
-- registry dates only. Old account-number guesses are deliberately ignored.
CREATE OR REPLACE TABLE `a4i_econ.businesses_enriched` AS
WITH source AS (
  SELECT business_id,name,legal_name,address,zip,naics,corridor,latitude,longitude,
    IF(REGEXP_CONTAINS(TRIM(CAST(naics AS STRING)),r'^\d{2,6}$'),
       SUBSTR(TRIM(CAST(naics AS STRING)),1,4),NULL) AS naics4,
    SAFE_CAST(SUBSTR(COALESCE(JSON_VALUE(TO_JSON_STRING(b),'$.location_start_date'),
                             JSON_VALUE(TO_JSON_STRING(b),'$.start_date')),1,10) AS DATE) AS location_start_date
  FROM `a4i_econ.businesses` b
), typed AS (
 SELECT *, LENGTH(naics4)=4 AND NOT ENDS_WITH(naics4,'00')
    AND naics4 NOT IN ('4445','5471','5400','3100','4400','7210','7220') AS specific_naics4,
  CASE
   WHEN STARTS_WITH(naics4,'721') THEN 'Accommodations'
   WHEN STARTS_WITH(naics4,'722') THEN 'Food Services'
   WHEN STARTS_WITH(naics4,'54') THEN 'Professional, Scientific, and Technical Services'
   WHEN SUBSTR(naics4,1,2) IN ('44','45') THEN 'Retail Trade'
   WHEN STARTS_WITH(naics4,'81') THEN 'Certain Services'
   WHEN SUBSTR(naics4,1,2) IN ('61','62') THEN 'Private Education and Health Services'
   WHEN STARTS_WITH(naics4,'51') THEN 'Information'
   WHEN SUBSTR(naics4,1,2) IN ('31','32','33') THEN 'Manufacturing'
   WHEN STARTS_WITH(naics4,'71') THEN 'Arts, Entertainment and Recreation'
   ELSE 'Unspecified / other' END AS industry_type
 FROM source
)
SELECT *, EXTRACT(YEAR FROM location_start_date) AS registration_year,
  DATE_DIFF(CURRENT_DATE('America/Toronto'),location_start_date,DAY)/365.2425 AS tenure_years,
  'SF registry location_start_date; NULL when absent' AS tenure_source,
  IF(specific_naics4,COUNT(*) OVER(PARTITION BY corridor,naics4)-1,NULL) AS corridor_peer_count
FROM typed;

-- One canonical prior per business: exact valid detail -> sector -> CA state.
-- The legacy sba_industry_failure_rates table/CSV is NOT consumed.
CREATE OR REPLACE TABLE `a4i_econ.business_risk` AS
SELECT b.business_id,COALESCE(r4.p_fail,r2.p_fail,rs.p_fail) AS p_fail,
 COALESCE(r4.p_fail_lo90,r2.p_fail_lo90,rs.p_fail_lo90) AS p_fail_lo90,
 COALESCE(r4.p_fail_hi90,r2.p_fail_hi90,rs.p_fail_hi90) AS p_fail_hi90,
 CASE WHEN r4.code IS NOT NULL THEN 'naics4' WHEN r2.code IS NOT NULL THEN 'naics2' ELSE 'state' END AS p_fail_level,
 COALESCE(r4.n_loans,r2.n_loans,rs.n_loans) AS rate_basis_loans,
 COALESCE(r4.basis,r2.basis,rs.basis) AS rate_basis,
 COALESCE(r4.horizon_months,r2.horizon_months,rs.horizon_months) AS horizon_months
FROM `a4i_econ.businesses_enriched` b
LEFT JOIN `a4i_econ.industry_failure_rates` r4 ON b.specific_naics4 AND r4.level='naics4' AND r4.code=b.naics4
LEFT JOIN `a4i_econ.industry_failure_rates` r2 ON r2.level='naics2' AND r2.code=SUBSTR(b.naics4,1,2)
CROSS JOIN (SELECT * FROM `a4i_econ.industry_failure_rates` WHERE level='state' AND code='CA') rs;

-- Require the same normalized street address. Missing street numbers are NOT
-- verification. Current loan balance/payment is not inferred from approval.
CREATE OR REPLACE TABLE `a4i_econ.borrowed_from_enriched` AS
SELECT CONCAT(c.business_id,'|',c.source_file,'|',c.bank_name,'|',CAST(c.approval_date AS STRING),'|',CAST(c.gross_approval AS STRING)) AS edge_id,
 c.business_id,c.bank_name,c.gross_approval AS loan_amount,DATE(c.approval_date) AS approval_date,
 c.loan_status,c.charged_off AS is_charged_off,c.address_check
FROM `a4i_econ.corridor_loan_outcomes` c
JOIN `a4i_econ.businesses_enriched` b USING(business_id)
WHERE c.address_check='same street address' AND UPPER(c.loan_status) NOT IN ('CANCLD','COMMIT')
 AND c.bank_name IS NOT NULL;
ASSERT (SELECT COUNT(*)=COUNT(DISTINCT edge_id) FROM `a4i_econ.borrowed_from_enriched`)
 AS 'Composite loan key collision: resolve against the source loan identifier';
CREATE OR REPLACE TABLE `a4i_econ.lenders_enriched` AS
SELECT bank_name,COUNT(*) AS loan_count,COUNT(DISTINCT business_id) AS borrowers,
 SUM(loan_amount) AS total_original_approvals,COUNTIF(is_charged_off) AS charged_off_loans
FROM `a4i_econ.borrowed_from_enriched` GROUP BY bank_name;

-- Buyer-specific alternative modeled suppliers of the same precise input.
CREATE OR REPLACE TABLE `a4i_econ.supplies_enriched` AS
SELECT e.edge_id,e.supplier_id,e.buyer_id,e.intensity,e.metres,
 e.intensity*EXP(-e.metres/400.0) AS decayed_intensity,
 COUNT(DISTINCT alt.supplier_id) AS buyer_input_alternatives,
 e.intensity*EXP(-e.metres/400.0)/(1+COUNT(DISTINCT alt.supplier_id)) AS adjusted_weight
FROM `a4i_econ.supplies` e
JOIN `a4i_econ.businesses_enriched` s ON s.business_id=e.supplier_id
JOIN `a4i_econ.businesses_enriched` b ON b.business_id=e.buyer_id
LEFT JOIN (
 SELECT x.buyer_id,x.supplier_id,p.naics4,p.specific_naics4,x.metres
 FROM `a4i_econ.supplies` x JOIN `a4i_econ.businesses_enriched` p ON p.business_id=x.supplier_id
) alt ON alt.buyer_id=e.buyer_id AND alt.supplier_id!=e.supplier_id AND alt.metres<=500
 AND s.specific_naics4 AND alt.specific_naics4 AND alt.naics4=s.naics4
WHERE e.supplier_id!=e.buyer_id AND e.intensity>0 AND e.intensity<=1 AND e.metres>=0
GROUP BY e.edge_id,e.supplier_id,e.buyer_id,e.intensity,e.metres;

CREATE OR REPLACE PROPERTY GRAPH a4i_econ.LocalEconomy
NODE TABLES (
  a4i_econ.businesses_enriched KEY (business_id)
    LABEL Business PROPERTIES (business_id, name, naics4, industry_type, latitude, longitude, registration_year, tenure_years),
  a4i_econ.employer_blocks KEY (block_id) LABEL Employer PROPERTIES (block_id, jobs),
  a4i_econ.lenders_enriched KEY (bank_name) LABEL Lender PROPERTIES (bank_name)
)
EDGE TABLES (
  a4i_econ.supplies_enriched KEY (edge_id)
    SOURCE KEY (supplier_id) REFERENCES businesses_enriched (business_id)
    DESTINATION KEY (buyer_id) REFERENCES businesses_enriched (business_id)
    LABEL Supplies PROPERTIES (intensity, metres, decayed_intensity, buyer_input_alternatives, adjusted_weight),
  a4i_econ.draws_footfall_from KEY (edge_id)
    SOURCE KEY (block_id) REFERENCES employer_blocks (block_id)
    DESTINATION KEY (business_id) REFERENCES businesses_enriched (business_id)
    LABEL DrawsFootfall PROPERTIES (worker_share, metres),
  a4i_econ.borrowed_from_enriched KEY (edge_id)
    SOURCE KEY (business_id) REFERENCES businesses_enriched (business_id)
    DESTINATION KEY (bank_name) REFERENCES lenders_enriched (bank_name)
    LABEL BorrowedFrom PROPERTIES (loan_amount, approval_date, loan_status, is_charged_off)
);

-- A: Actual growth in distinct destinations at depths 1..8. ANY SHORTEST
-- avoids enumerating all walks. Depth is topology, not a probability of failure.
WITH destinations AS (
 SELECT * FROM GRAPH_TABLE(a4i_econ.LocalEconomy
  MATCH ANY SHORTEST (s:Business)-[e:Supplies]->{1,8}(d:Business)
  WHERE s.business_id!=d.business_id
  RETURN s.business_id AS root,d.business_id AS destination,ARRAY_LENGTH(e) AS shortest_hop)
)
SELECT root,h AS max_hops,COUNTIF(shortest_hop=h) AS new_destinations,
 COUNTIF(shortest_hop<=h) AS cumulative_destinations
FROM destinations CROSS JOIN UNNEST(GENERATE_ARRAY(1,8)) h GROUP BY root,h ORDER BY root,h;

-- B: Keystone band through NEXT ... FILTER. Not a grant approval.
GRAPH a4i_econ.LocalEconomy
MATCH ANY SHORTEST (seed:Business)-[:Supplies]->{1,2}(dst:Business)
WHERE seed.business_id!=dst.business_id
RETURN seed.business_id AS business_id,seed.name AS name,COUNT(DISTINCT dst.business_id) AS exposed
NEXT FILTER exposed>=5 AND exposed<=25
RETURN business_id,name,exposed ORDER BY exposed DESC;

-- C: Unique endpoint weighting (strongest path per endpoint, two-hop baseline).
-- Raw and decayed variants include EVERY business; no industry is pre-excluded.
WITH paths AS (
 SELECT supplier_id AS root,buyer_id AS dst,
  intensity/(1+buyer_input_alternatives) AS raw_w,adjusted_weight AS decay_w
 FROM `a4i_econ.supplies_enriched`
 UNION ALL
 SELECT a.supplier_id,b.buyer_id,
  a.intensity/(1+a.buyer_input_alternatives)*b.intensity/(1+b.buyer_input_alternatives),
  a.adjusted_weight*b.adjusted_weight
 FROM `a4i_econ.supplies_enriched` a JOIN `a4i_econ.supplies_enriched` b ON a.buyer_id=b.supplier_id
 WHERE a.supplier_id!=b.buyer_id
), endpoint AS (
 SELECT root,dst,MAX(raw_w) AS raw_w,MAX(decay_w) AS decay_w FROM paths GROUP BY root,dst
), consequence AS (
 SELECT root,COUNT(*) AS reach_2hop,SUM(raw_w) AS exposure_before_decay,SUM(decay_w) AS exposure_after_decay
 FROM endpoint GROUP BY root
)
SELECT b.business_id,b.name,b.industry_type,COALESCE(c.reach_2hop,0) AS reach_2hop,
 COALESCE(c.reach_2hop BETWEEN 5 AND 25,FALSE) AS cascade_case,
 r.p_fail,r.p_fail_level,r.p_fail*COALESCE(c.reach_2hop,0) AS old_expected_exposed,
 r.p_fail*COALESCE(c.exposure_after_decay,0) AS new_expected_exposure,
 ROW_NUMBER() OVER(ORDER BY COALESCE(c.exposure_before_decay,0) DESC,b.business_id) AS rank_before_decay,
 ROW_NUMBER() OVER(ORDER BY COALESCE(c.exposure_after_decay,0) DESC,b.business_id) AS rank_after_decay
FROM `a4i_econ.businesses_enriched` b LEFT JOIN consequence c ON c.root=b.business_id
LEFT JOIN `a4i_econ.business_risk` r USING(business_id) ORDER BY rank_after_decay;

-- D: Employer -> storefront <- supplier. Aggregate each edge type BEFORE joining,
-- otherwise a cafe with five suppliers would multiply its worker share by five.
WITH foot AS (
 SELECT DISTINCT block_id,business_id,worker_share FROM `a4i_econ.draws_footfall_from`
), exposure AS (
 SELECT block_id,COUNT(DISTINCT business_id) AS storefronts,SUM(worker_share) AS allocated_worker_share
 FROM foot GROUP BY block_id
), upstream AS (
 SELECT f.block_id,COUNT(DISTINCT e.supplier_id) AS upstream_suppliers
 FROM foot f JOIN `a4i_econ.supplies_enriched` e ON e.buyer_id=f.business_id GROUP BY f.block_id
)
SELECT exposure.*,COALESCE(upstream.upstream_suppliers,0) AS upstream_suppliers
FROM exposure LEFT JOIN upstream USING(block_id) ORDER BY allocated_worker_share DESC;

-- E: Downstream borrowers, including businesses with no matched SBA history.
WITH reached AS (
 SELECT DISTINCT root,destination FROM GRAPH_TABLE(a4i_econ.LocalEconomy
  MATCH ANY SHORTEST (s:Business)-[:Supplies]->{1,2}(d:Business)
  WHERE s.business_id!=d.business_id
  RETURN s.business_id AS root,d.business_id AS destination)
)
SELECT r.root,r.destination,b.name,l.bank_name,l.loan_status,l.is_charged_off,
 CASE WHEN l.edge_id IS NULL THEN 'No address-checked match; debt is unknown' ELSE 'Historical matched loan; not current distress' END AS evidence
FROM reached r JOIN `a4i_econ.businesses_enriched` b ON b.business_id=r.destination
LEFT JOIN `a4i_econ.borrowed_from_enriched` l ON l.business_id=r.destination;

-- F: Industry variety: report source denominators, not a narrative assertion.
SELECT industry_type,COUNT(*) AS locations,
 SAFE_DIVIDE(COUNT(*),SUM(COUNT(*)) OVER()) AS share
FROM `a4i_econ.businesses_enriched` GROUP BY industry_type ORDER BY locations DESC;

-- G: Duplicate-name audit. These remain SEPARATE locations until a documented
-- entity-resolution decision justifies a merge, including both source addresses.
SELECT LOWER(TRIM(name)) AS name_key,COUNT(*) AS locations,
 ARRAY_AGG(STRUCT(business_id,address,legal_name)) AS records
FROM `a4i_econ.businesses_enriched` GROUP BY name_key HAVING COUNT(*)>1;
